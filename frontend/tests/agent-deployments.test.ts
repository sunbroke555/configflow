import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { defineComponent } from 'vue'
import { flushPromises, mount } from '@vue/test-utils'
import { agentApi } from '@/api'
import { notify } from '@/lib/feedback'
import { deploymentStatusLabel, useAgentDeployments } from '@/composables/useAgentDeployments'

vi.mock('@/api', () => ({ agentApi: { getDeployment: vi.fn(), activateDeployment: vi.fn(), rollbackDeployment: vi.fn(), pushConfig: vi.fn() } }))
vi.mock('@/lib/feedback', () => ({ notify: { success: vi.fn(), error: vi.fn() } }))
const wrappers: ReturnType<typeof mount>[] = []
function render(shouldAnnounce?: Parameters<typeof useAgentDeployments>[1]) {
  let flow!: ReturnType<typeof useAgentDeployments>
  const onSuccess = vi.fn()
  wrappers.push(mount(defineComponent({ setup() { flow = useAgentDeployments(onSuccess, shouldAnnounce); return () => null } })))
  return { flow, onSuccess }
}
beforeEach(() => { vi.useFakeTimers(); vi.clearAllMocks() })
afterEach(() => { wrappers.splice(0).forEach(w => w.unmount()); vi.useRealTimers() })

describe('Agent deployment lifecycle feedback', () => {
  it('keeps tracking a submitted task without announcing after its editor session ends', async () => {
    let active = true
    const { flow, onSuccess } = render(() => active)
    vi.mocked(agentApi.getDeployment).mockResolvedValueOnce({ data: { deployment_id: 'background', status: 'succeeded' } } as any)
    flow.track('agent-1', { deployment_id: 'background', status: 'verifying' })
    active = false
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1'].status).toBe('succeeded')
    expect(notify.success).not.toHaveBeenCalled()
    expect(onSuccess).not.toHaveBeenCalled()
  })

  it('polls during submission and treats registration 404s as pending rather than retryable', async () => {
    const { flow } = render()
    vi.mocked(agentApi.getDeployment)
      .mockRejectedValueOnce({ response: { status: 404 } })
      .mockResolvedValueOnce({ data: { deployment_id: 'slow-post', status: 'uploading' } } as any)
    expect(flow.beginSubmission('agent-1', 'slow-post')).toBe(true)
    expect(flow.beginSubmission('agent-1', 'duplicate')).toBe(false)
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1']).toMatchObject({ deployment_id: 'slow-post', status: 'preparing', query_error: false })
    expect(flow.deployments['agent-1'].not_recorded).toBeFalsy()
    await flow.retryPublish('agent-1')
    expect(agentApi.pushConfig).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(2000)
    expect(flow.deployments['agent-1'].status).toBe('uploading')
    flow.endSubmission('agent-1', 'slow-post', { deployment_id: 'slow-post', status: 'preparing' })
    expect(flow.deployments['agent-1'].status).toBe('uploading')
  })

  it.each(['unknown', 'rejected'] as const)('keeps polled completion after a late submission %s', async result => {
    const { flow, onSuccess } = render()
    vi.mocked(agentApi.getDeployment).mockResolvedValueOnce({ data: { deployment_id: 'finished-post', status: 'succeeded' } } as any)
    flow.beginSubmission('agent-1', 'finished-post')
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.beginSubmission('agent-1', 'duplicate')).toBe(false)
    expect(flow.endSubmission('agent-1', 'finished-post', result)).toBe(true)
    await vi.advanceTimersByTimeAsync(10000)
    expect(flow.deployments['agent-1']).toMatchObject({ status: 'succeeded', query_error: false })
    expect(agentApi.getDeployment).toHaveBeenCalledOnce()
    expect(onSuccess).toHaveBeenCalledOnce()
    expect(notify.error).not.toHaveBeenCalled()
  })

  it('keeps confirming the same ID after an unobserved submission times out', async () => {
    const { flow } = render()
    vi.mocked(agentApi.getDeployment)
      .mockRejectedValueOnce({ response: { status: 404 } })
      .mockRejectedValueOnce({ response: { status: 404 } })
      .mockResolvedValueOnce({ data: { deployment_id: 'timeout-post', status: 'succeeded' } } as any)
    flow.beginSubmission('agent-1', 'timeout-post')
    await vi.advanceTimersByTimeAsync(0)
    flow.endSubmission('agent-1', 'timeout-post', 'unknown')
    expect(flow.deployments['agent-1'].status).toBe('unknown')
    await vi.advanceTimersByTimeAsync(2000)
    expect(flow.deployments['agent-1'].not_recorded).toBe(true)
    await vi.advanceTimersByTimeAsync(5000)
    expect(agentApi.getDeployment).toHaveBeenLastCalledWith('agent-1', 'timeout-post')
    expect(flow.deployments['agent-1'].status).toBe('succeeded')
  })

  it('clears a definitive pre-submission rejection without retaining the busy state', async () => {
    const { flow } = render()
    vi.mocked(agentApi.getDeployment).mockRejectedValueOnce({ response: { status: 404 } })
    flow.beginSubmission('agent-1', 'rejected-post')
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.endSubmission('agent-1', 'rejected-post', 'rejected')).toBe(false)
    await vi.advanceTimersByTimeAsync(10000)
    expect(flow.deployments['agent-1']).toBeUndefined()
    expect(flow.busy('agent-1')).toBe(false)
    expect(agentApi.getDeployment).toHaveBeenCalledOnce()
  })

  it('continues polling when the POST settles during an older in-flight status request', async () => {
    const { flow } = render()
    let resolvePoll!: (value: any) => void
    vi.mocked(agentApi.getDeployment)
      .mockImplementationOnce(() => new Promise(resolve => { resolvePoll = resolve }))
      .mockResolvedValueOnce({ data: { deployment_id: 'racing-post', status: 'succeeded' } } as any)
    flow.beginSubmission('agent-1', 'racing-post')
    await vi.advanceTimersByTimeAsync(0)
    flow.endSubmission('agent-1', 'racing-post', { deployment_id: 'racing-post', status: 'verifying' })
    await vi.advanceTimersByTimeAsync(2000)
    resolvePoll({ data: { deployment_id: 'racing-post', status: 'preparing' } })
    await flushPromises()
    expect(flow.deployments['agent-1'].status).toBe('verifying')
    await vi.advanceTimersByTimeAsync(2000)
    expect(flow.deployments['agent-1'].status).toBe('succeeded')
    expect(agentApi.getDeployment).toHaveBeenCalledTimes(2)
  })

  it('does not resume pending submission polls or report results after unmount', async () => {
    const { flow, onSuccess } = render()
    let resolvePoll!: (value: any) => void
    vi.mocked(agentApi.getDeployment).mockImplementationOnce(() => new Promise(resolve => { resolvePoll = resolve }))
    flow.beginSubmission('agent-1', 'closed-post')
    await vi.advanceTimersByTimeAsync(0)
    wrappers.splice(0).forEach(wrapper => wrapper.unmount())
    resolvePoll({ data: { deployment_id: 'closed-post', status: 'succeeded' } })
    flow.endSubmission('agent-1', 'closed-post', { deployment_id: 'closed-post', status: 'succeeded' })
    await flushPromises()
    await vi.advanceTimersByTimeAsync(10000)
    expect(agentApi.getDeployment).toHaveBeenCalledOnce()
    expect(onSuccess).not.toHaveBeenCalled()
    expect(notify.success).not.toHaveBeenCalled()
  })

  it('rolls back the current successful deployment and reports success only after restored service checks', async () => {
    const { flow, onSuccess } = render()
    flow.track('agent-1', { deployment_id: 'good-1', status: 'succeeded' }, false)
    vi.mocked(agentApi.rollbackDeployment).mockResolvedValue({ data: { deployment_id: 'good-1', status: 'rolling_back', manual_rollback: true } } as any)
    vi.mocked(agentApi.getDeployment).mockResolvedValue({ data: { deployment_id: 'good-1', status: 'rolled_back', manual_rollback: true } } as any)
    await flow.rollback('agent-1', 'good-1')
    expect(agentApi.rollbackDeployment).toHaveBeenCalledExactlyOnceWith('agent-1', 'good-1')
    expect(flow.busy('agent-1')).toBe(true)
    expect(notify.success).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(2000)
    expect(flow.busy('agent-1')).toBe(false)
    expect(notify.success).toHaveBeenCalledWith('手动回滚成功，发布前配置已恢复并通过服务检查')
    expect(notify.error).not.toHaveBeenCalled()
    expect(onSuccess).toHaveBeenCalledOnce()
  })

  it('rejects old targets and duplicate clicks, and restores the prior state after an explicit conflict', async () => {
    const { flow } = render()
    flow.track('agent-1', { deployment_id: 'current', status: 'succeeded' }, false)
    let reject!: (error: unknown) => void
    vi.mocked(agentApi.rollbackDeployment).mockImplementationOnce(() => new Promise((_resolve, fail) => { reject = fail }))
    await flow.rollback('agent-1', 'old')
    expect(agentApi.rollbackDeployment).not.toHaveBeenCalled()
    const operation = flow.rollback('agent-1', 'current')
    await flow.rollback('agent-1', 'current')
    expect(agentApi.rollbackDeployment).toHaveBeenCalledOnce()
    reject({ response: { status: 409, data: { message: '备份已不存在' } } })
    await operation
    expect(flow.deployments['agent-1']).toMatchObject({ deployment_id: 'current', status: 'succeeded', query_error: false, rollback_rejected: true, rollback_message: '备份已不存在' })
    expect(flow.busy('agent-1')).toBe(false)
    expect(notify.error).toHaveBeenCalledWith('无法手动回滚', '备份已不存在')
  })

  it('does not treat a stale successful publication as confirmation of a timed-out rollback', async () => {
    const { flow } = render()
    flow.track('agent-1', { deployment_id: 'current', status: 'succeeded' }, false)
    vi.mocked(agentApi.rollbackDeployment).mockRejectedValueOnce(new Error('transport lost'))
    vi.mocked(agentApi.getDeployment)
      .mockResolvedValueOnce({ data: { deployment_id: 'current', status: 'succeeded' } } as any)
      .mockResolvedValueOnce({ data: { deployment_id: 'current', status: 'rolled_back', manual_rollback: true } } as any)
    await flow.rollback('agent-1', 'current')
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1']).toMatchObject({ status: 'unknown', manual_rollback: true })
    expect(notify.success).not.toHaveBeenCalled()
    await flow.retryPublish('agent-1')
    expect(agentApi.pushConfig).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(2000)
    expect(flow.deployments['agent-1'].status).toBe('rolled_back')
    expect(notify.success).toHaveBeenCalledOnce()
  })

  it('ends an uncertain rollback after an explicit server rejection without reporting publication success', async () => {
    const { flow, onSuccess } = render()
    flow.track('agent-1', { deployment_id: 'current', status: 'succeeded' }, false)
    vi.mocked(agentApi.rollbackDeployment).mockRejectedValueOnce(new Error('transport lost'))
    const rejection = { deployment_id: 'current', status: 'succeeded', rollback_rejected: true, rollback_message: '备份已不可用' }
    vi.mocked(agentApi.getDeployment).mockResolvedValueOnce({ data: rejection } as any)
    await flow.rollback('agent-1', 'current')
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1']).toMatchObject({ status: 'succeeded', manual_rollback: false, rollback_rejected: true, query_error: false })
    expect(flow.busy('agent-1')).toBe(false)
    expect(deploymentStatusLabel(flow.deployments['agent-1'])).toBe('手动回滚未执行')
    expect(notify.error).toHaveBeenCalledExactlyOnceWith('无法手动回滚', '备份已不可用')
    expect(notify.success).not.toHaveBeenCalled()
    expect(onSuccess).toHaveBeenCalledOnce()
    flow.track('agent-1', rejection)
    await vi.advanceTimersByTimeAsync(10000)
    expect(agentApi.getDeployment).toHaveBeenCalledOnce()
    expect(notify.error).toHaveBeenCalledOnce()
    vi.mocked(agentApi.rollbackDeployment).mockRejectedValueOnce(new Error('transport lost again'))
    vi.mocked(agentApi.getDeployment).mockResolvedValueOnce({ data: rejection } as any)
    await flow.rollback('agent-1', 'current')
    expect(deploymentStatusLabel(flow.deployments['agent-1'])).toBe('手动回滚结果待确认')
    await vi.advanceTimersByTimeAsync(0)
    expect(notify.error).toHaveBeenCalledTimes(2)
    expect(onSuccess).toHaveBeenCalledTimes(2)
    vi.mocked(agentApi.rollbackDeployment).mockResolvedValueOnce({ data: { deployment_id: 'current', status: 'rolling_back', manual_rollback: true } } as any)
    await flow.rollback('agent-1', 'current')
    expect(deploymentStatusLabel(flow.deployments['agent-1'])).toBe('正在恢复发布前配置')
    expect(flow.deployments['agent-1'].rollback_rejected).toBeUndefined()
  })

  it('shows a persisted rejection without a false success toast when opening the Agent page', () => {
    const { flow, onSuccess } = render()
    flow.track('agent-1', { deployment_id: 'current', status: 'succeeded', rollback_rejected: true, rollback_message: '活动版本已变更' }, false)
    expect(notify.success).not.toHaveBeenCalled()
    expect(notify.error).not.toHaveBeenCalled()
    expect(onSuccess).not.toHaveBeenCalled()
    expect(flow.busy('agent-1')).toBe(false)
  })

  it('does not claim success on receipt; waits for core health checks to pass', async () => {
    const { flow, onSuccess } = render()
    vi.mocked(agentApi.getDeployment)
      .mockResolvedValueOnce({ data: { deployment_id: 'publish-1', status: 'checking' } } as any)
      .mockResolvedValueOnce({ data: { deployment_id: 'publish-1', status: 'succeeded' } } as any)
    flow.track('agent-1', { deployment_id: 'publish-1', status: 'receiving' })
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1'].status).toBe('checking')
    expect(notify.success).not.toHaveBeenCalled()
    expect(flow.busy('agent-1')).toBe(true)
    await vi.advanceTimersByTimeAsync(2000)
    expect(notify.success).toHaveBeenCalledTimes(1)
    expect(onSuccess).toHaveBeenCalledTimes(1)
    expect(flow.busy('agent-1')).toBe(false)
  })

  it('keeps the same deployment across transport failures and reports rollback', async () => {
    const { flow } = render()
    vi.mocked(agentApi.getDeployment)
      .mockRejectedValueOnce(new Error('connection lost'))
      .mockResolvedValueOnce({ data: { deployment_id: 'publish-2', status: 'rolled_back', error: 'Core failed to start' } } as any)
    flow.track('agent-1', { deployment_id: 'publish-2', status: 'starting' })
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1'].query_error).toBe(true)
    expect(flow.busy('agent-1')).toBe(true)
    expect(notify.error).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(5000)
    expect(agentApi.getDeployment).toHaveBeenLastCalledWith('agent-1', 'publish-2')
    expect(notify.error).toHaveBeenCalledWith('发布失败，已回滚', 'Core failed to start')
    expect(notify.success).not.toHaveBeenCalled()
  })

  it('activates a staged version through its existing deployment rather than a restart', async () => {
    const { flow } = render()
    flow.track('agent-1', { deployment_id: 'staged-1', status: 'ready' })
    vi.mocked(agentApi.activateDeployment).mockResolvedValueOnce({ data: { deployment_id: 'staged-1', status: 'starting' } } as any)
    await flow.activate('agent-1')
    expect(agentApi.activateDeployment).toHaveBeenCalledWith('agent-1', 'staged-1')
    expect(flow.busy('agent-1')).toBe(true)
    expect(notify.success).not.toHaveBeenCalled()
  })

  it('retries when the backend returns a cached state while the Agent is unreachable', async () => {
    const { flow } = render()
    vi.mocked(agentApi.getDeployment)
      .mockResolvedValueOnce({ data: { deployment_id: 'pending-1', status: 'checking', pending: true } } as any)
      .mockResolvedValueOnce({ data: { deployment_id: 'pending-1', status: 'succeeded' } } as any)
    flow.track('agent-1', { deployment_id: 'pending-1', status: 'checking' })
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1'].query_error).toBe(true)
    expect(notify.success).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(5000)
    expect(flow.deployments['agent-1'].query_error).toBe(false)
    expect(notify.success).toHaveBeenCalledTimes(1)
  })

  it('resumes persisted tasks, and stops polling when the page is closed', async () => {
    const { flow } = render()
    vi.mocked(agentApi.getDeployment).mockResolvedValue({ data: { deployment_id: 'resume-1', status: 'checking' } } as any)
    flow.track('agent-1', { deployment_id: 'resume-1', status: 'starting' }, false)
    await vi.advanceTimersByTimeAsync(0)
    wrappers.splice(0).forEach(w => w.unmount())
    await flushPromises()
    await vi.advanceTimersByTimeAsync(10000)
    expect(agentApi.getDeployment).toHaveBeenCalledTimes(1)
    expect(notify.success).not.toHaveBeenCalled()
  })

  it('does not regress a completed publication after a late list response or poll failure', async () => {
    const { flow, onSuccess } = render()
    let rejectPoll!: (reason: unknown) => void
    vi.mocked(agentApi.getDeployment).mockImplementationOnce(() => new Promise((_resolve, reject) => { rejectPoll = reject }))
    flow.track('agent-1', { deployment_id: 'complete-1', status: 'checking' })
    await vi.advanceTimersByTimeAsync(0)
    flow.track('agent-1', { deployment_id: 'complete-1', status: 'succeeded' })
    flow.track('agent-1', { deployment_id: 'complete-1', status: 'ready' }, false)
    rejectPoll(new Error('old poll failed'))
    await flushPromises()
    await vi.advanceTimersByTimeAsync(5000)
    expect(flow.deployments['agent-1'].status).toBe('succeeded')
    expect(flow.deployments['agent-1'].query_error).toBe(false)
    expect(agentApi.getDeployment).toHaveBeenCalledTimes(1)
    expect(onSuccess).toHaveBeenCalledTimes(1)
  })

  it('keeps a missing publication unknown and retries with its original identity', async () => {
    const { flow } = render()
    vi.mocked(agentApi.getDeployment)
      .mockRejectedValueOnce({ response: { status: 404 } })
      .mockResolvedValueOnce({ data: { deployment_id: 'missing-1', status: 'succeeded' } } as any)
    vi.mocked(agentApi.pushConfig).mockResolvedValueOnce({ data: { deployment_id: 'missing-1', status: 'checking' } } as any)
    flow.track('agent-1', { deployment_id: 'missing-1', status: 'unknown' })
    await vi.advanceTimersByTimeAsync(0)
    expect(flow.deployments['agent-1']).toMatchObject({ status: 'unknown', not_recorded: true })
    expect(flow.busy('agent-1')).toBe(true)
    expect(notify.error).not.toHaveBeenCalled()
    await flow.retryPublish('agent-1')
    expect(agentApi.pushConfig).toHaveBeenCalledExactlyOnceWith('agent-1', 'missing-1')
    expect(flow.deployments['agent-1'].status).toBe('checking')
    expect(flow.deployments['agent-1'].not_recorded).toBeFalsy()
    await vi.advanceTimersByTimeAsync(2000)
    expect(flow.deployments['agent-1'].status).toBe('succeeded')
  })

  it('prevents duplicate retry clicks and keeps querying the same ID when the retry times out', async () => {
    const { flow } = render()
    let rejectRetry!: (reason: unknown) => void
    vi.mocked(agentApi.getDeployment).mockRejectedValue({ response: { status: 404 } })
    vi.mocked(agentApi.pushConfig).mockImplementationOnce(() => new Promise((_resolve, reject) => { rejectRetry = reject }))
    flow.track('agent-1', { deployment_id: 'retry-1', status: 'unknown' })
    await vi.advanceTimersByTimeAsync(0)
    const retry = flow.retryPublish('agent-1')
    await flow.retryPublish('agent-1')
    expect(flow.deployments['agent-1'].retrying).toBe(true)
    expect(agentApi.pushConfig).toHaveBeenCalledExactlyOnceWith('agent-1', 'retry-1')
    rejectRetry(new Error('timeout'))
    await retry
    expect(flow.deployments['agent-1']).toMatchObject({ status: 'unknown', retrying: false, query_error: true })
    await vi.advanceTimersByTimeAsync(5000)
    expect(agentApi.getDeployment).toHaveBeenLastCalledWith('agent-1', 'retry-1')
    expect(flow.deployments['agent-1'].not_recorded).toBe(true)
    expect(notify.error).not.toHaveBeenCalled()
  })
})

describe('Agent failure response diagnostics', () => {
  it('retains diagnostic output when activation remains uncertain', async () => {
    const { flow } = render()
    flow.track('one', { deployment_id: 'ready', status: 'ready' }, false)
    vi.mocked(agentApi.activateDeployment).mockRejectedValueOnce({ response: { status: 503, data: { message: 'response interrupted', error_details: 'failed to read core status' } } })
    await flow.activate('one')
    expect(flow.deployments.one).toMatchObject({ status: 'unknown', query_error: true, error_details: 'failed to read core status' })
  })
  it('keeps rollback rejection details without changing the successful deployment or retry eligibility', async () => {
    const { flow } = render()
    flow.track('one', { deployment_id: 'active', status: 'succeeded' }, false)
    vi.mocked(agentApi.rollbackDeployment).mockRejectedValueOnce({ response: { status: 409, data: { message: 'backup unavailable', error_details: 'missing previous/config.yaml' } } })
    await flow.rollback('one', 'active')
    expect(flow.deployments.one).toMatchObject({ status: 'succeeded', rollback_rejected: true, rollback_error_details: 'missing previous/config.yaml' })
    expect(deploymentStatusLabel(flow.deployments.one)).toBe('手动回滚未执行')
    expect(flow.busy('one')).toBe(false)
  })
})
